; diagstub.s - fixed-address data block for the psramdiag ROM.
;
; Places a 256-byte walking pattern at exactly Z80 address 0x5000
; (PATTERN_ADDR), inside the cart page 0x4000..0xBFFF, so psramdiag.c
; can reference it at a FIXED address - that lets the logic analyzer
; trigger on the address bus alone (A=0x50xx).
;
; Pattern formula: byte[i] = i ^ 0xA5   (matches psramdiag.c PH4 and
; tools/rom2c.py's integrity pre-check).
;
; PH1 reads 0x5000, PH3 reads 0x5040, PH5 reads 0x5080 - all inside
; this pattern, each with a distinct expected data byte (0xA5 / 0xE5 /
; 0x25) usable as a second LA qualifier.
;
; Code (.area _CODE at --code-loc 0x4020) stays well below 0x5000, so
; there is no overlap with this block. Assembled with sdasz80.

